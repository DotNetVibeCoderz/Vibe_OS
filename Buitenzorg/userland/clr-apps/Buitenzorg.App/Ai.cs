// Buitenzorg.AI: the OS's built-in AI for apps -- a local language model
// (GGUF llama models; /disk/STORIES.GGU is on every image), simple computer
// vision on pictures, and the name of the GPU compute backend. The work runs
// in the host (clrhost aiapi.rs + llm.rs); matrix products go to the GPU
// through the kernel's COMPUTE_OP when the machine has one.
//
// Off the device (`dotnet X.dll --selftest`) a small simulated model answers
// with deterministic text, and Vision runs in C#, so apps test on a PC.

using System.Collections.Generic;

namespace Buitenzorg.AI;

internal static class AiNative
{
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiLoad(string path, int flags);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern long AiInfo(int model, int what);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern string AiText(int model, int what);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiBegin(int model, string prompt, int steps, int tempMilli, long seed);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern string? AiNext(int model);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern string? AiGenerate(int model, string prompt, int steps, int tempMilli, long seed);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiTokens(int model, string text);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern void AiFree(int model);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiEdges(int[] src, int w, int h, int[] dst);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiGray(int[] src, int w, int h, int[] dst);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern int AiHistogram(int[] src, int[] bins);
    [System.Runtime.InteropServices.DllImport("buitenzorg")] internal static extern string AiCompute();

    static int _state; // 0 unknown, 1 on Buitenzorg, 2 simulated
    /// <summary>True when the host natives are there (on Buitenzorg).</summary>
    internal static bool Present
    {
        get
        {
            if (_state == 0)
            {
                try { AiCompute(); _state = 1; }
                catch (Exception e) when (e is DllNotFoundException || e is EntryPointNotFoundException) { _state = 2; }
            }
            return _state == 1;
        }
    }
}

/// <summary>Where a model's matrix products run.</summary>
public enum Accelerator
{
    /// <summary>The GPU when the kernel has a compute backend, else the CPU.</summary>
    Auto,
    /// <summary>Always the CPU.</summary>
    Cpu,
    /// <summary>Through COMPUTE_OP even when the backend is the kernel's CPU reference (tests the path).</summary>
    Gpu,
}

/// <summary>A local language model (GGUF, llama architecture). Load it once,
/// then <see cref="Generate"/>, <see cref="Stream"/> or <see cref="Begin"/>
/// text from a prompt. One generation at a time per model.</summary>
/// <example><code>
/// using var model = LanguageModel.Load();
/// Console.WriteLine(model.Generate("Once upon a time", maxTokens: 40));
/// </code></example>
public sealed class LanguageModel : IDisposable
{
    /// <summary>The model every Buitenzorg image carries (stories260K, MIT licence).</summary>
    public const string DefaultPath = "/disk/STORIES.GGU";

    int _id;
    SimModel? _sim;

    public string Path { get; private set; } = "";
    public int Layers { get; private set; }
    public int Dimension { get; private set; }
    public int Heads { get; private set; }
    public int KvHeads { get; private set; }
    public int Vocabulary { get; private set; }
    /// <summary>Tokens of prompt + answer the model can look at.</summary>
    public int ContextLength { get; private set; }
    public long Parameters { get; private set; }
    /// <summary>"CPU", the GPU backend's name, or "simulasi" off the device.</summary>
    public string Backend => _sim != null ? "simulasi" : AiNative.AiText(_id, 1);
    public bool OnGpu => _sim == null && AiNative.AiInfo(_id, 7) == 1;
    /// <summary>True off the device: a stand-in model, not the real one.</summary>
    public bool IsSimulated => _sim != null;

    /// <summary>Tokens generated by the last run, its prompt tokens and time.</summary>
    public int LastTokens => _sim != null ? _sim.LastTokens : (int)AiNative.AiInfo(_id, 8);
    public int LastPromptTokens => _sim != null ? _sim.LastPrompt : (int)AiNative.AiInfo(_id, 10);
    public int LastMilliseconds => _sim != null ? _sim.LastMs : (int)AiNative.AiInfo(_id, 9);
    public double LastTokensPerSecond => LastTokens == 0 ? 0 : LastTokens * 1000.0 / Math.Max(1, LastMilliseconds);

    /// <summary>Why the last <see cref="Load"/> returned null.</summary>
    public static string LastError { get; private set; } = "";

    LanguageModel() { }

    /// <summary>Load a model file (default: <see cref="DefaultPath"/>). Loading the
    /// same file again in one process returns the already loaded model. Null on
    /// failure, with the reason in <see cref="LastError"/>.</summary>
    public static LanguageModel? Load(string? path = null, Accelerator accelerator = Accelerator.Auto)
    {
        path ??= DefaultPath;
        if (!AiNative.Present)
        {
            LastError = "";
            return new LanguageModel { _sim = new SimModel(), Path = path, Layers = 5, Dimension = 64, Heads = 8, KvHeads = 4, Vocabulary = 512, ContextLength = 512, Parameters = 260_000 };
        }
        int flags = accelerator == Accelerator.Cpu ? 1 : accelerator == Accelerator.Gpu ? 2 : 0;
        int id = AiNative.AiLoad(path, flags);
        if (id <= 0)
        {
            LastError = id switch
            {
                -1 => path + ": berkas tidak ada",
                -2 => path + ": bukan berkas GGUF",
                _ => path + ": model tidak didukung (hanya arsitektur llama, F32/F16/Q8_0/Q4_0)",
            };
            return null;
        }
        LastError = "";
        return new LanguageModel
        {
            _id = id,
            Path = path,
            Layers = (int)AiNative.AiInfo(id, 0),
            Dimension = (int)AiNative.AiInfo(id, 1),
            Heads = (int)AiNative.AiInfo(id, 2),
            KvHeads = (int)AiNative.AiInfo(id, 3),
            Vocabulary = (int)AiNative.AiInfo(id, 4),
            ContextLength = (int)AiNative.AiInfo(id, 5),
            Parameters = AiNative.AiInfo(id, 6),
        };
    }

    static int Milli(double t) => (int)Math.Round(Math.Clamp(t, 0, 5) * 1000);
    static long Seed(long s) => s != 0 ? s : Environment.TickCount64;

    /// <summary>Continue <paramref name="prompt"/> with up to <paramref name="maxTokens"/>
    /// tokens. Temperature 0 = always the most likely token (the same answer every
    /// time); higher = more varied.</summary>
    public string Generate(string prompt, int maxTokens = 48, double temperature = 0, long seed = 0)
    {
        if (_sim != null) return _sim.Generate(prompt, maxTokens);
        return AiNative.AiGenerate(_id, prompt, maxTokens, Milli(temperature), Seed(seed)) ?? "";
    }

    /// <summary>Start a generation and take its text piece by piece with
    /// <see cref="Generation.Next"/> -- one call per UI frame shows the answer
    /// as it is written.</summary>
    public Generation Begin(string prompt, int maxTokens = 48, double temperature = 0, long seed = 0)
    {
        if (_sim != null) return new Generation(this, _sim.Begin(prompt, maxTokens));
        AiNative.AiBegin(_id, prompt, maxTokens, Milli(temperature), Seed(seed));
        return new Generation(this, null);
    }

    /// <summary>The answer as a sequence of text pieces.</summary>
    public IEnumerable<string> Stream(string prompt, int maxTokens = 48, double temperature = 0, long seed = 0)
    {
        var g = Begin(prompt, maxTokens, temperature, seed);
        string? piece;
        while ((piece = g.Next()) != null) yield return piece;
    }

    /// <summary>How many tokens the model reads <paramref name="text"/> as.</summary>
    public int CountTokens(string text) => _sim != null ? SimModel.Words(text).Count : AiNative.AiTokens(_id, text);

    internal string? NextPiece(Queue<string>? sim)
    {
        if (sim != null)
        {
            if (sim.Count == 0) return null;
            _sim!.LastTokens++;
            return sim.Dequeue();
        }
        return AiNative.AiNext(_id);
    }

    public void Dispose()
    {
        if (_id > 0) AiNative.AiFree(_id);
        _id = 0;
    }
}

/// <summary>A generation in progress (<see cref="LanguageModel.Begin"/>).</summary>
public sealed class Generation
{
    readonly LanguageModel _model;
    readonly Queue<string>? _sim;
    public bool IsDone { get; private set; }
    /// <summary>The text so far.</summary>
    public string Text { get; private set; } = "";

    internal Generation(LanguageModel model, Queue<string>? sim) { _model = model; _sim = sim; }

    /// <summary>The next piece of text, or null when the answer is complete.</summary>
    public string? Next()
    {
        if (IsDone) return null;
        var p = _model.NextPiece(_sim);
        if (p == null) { IsDone = true; return null; }
        Text += p;
        return p;
    }
}

/// <summary>The stand-in model off the device: a short story built from the
/// prompt's words, one word per token -- deterministic, so tests can check it.</summary>
sealed class SimModel
{
    static readonly string[] Story =
    {
        "there", "was", "a", "little", "girl", "named", "Lily.", "She", "loved", "to", "play", "in", "the", "garden",
        "with", "her", "friend", "the", "frog.", "One", "day", "they", "found", "a", "big", "green", "leaf", "and",
        "made", "a", "boat.", "They", "were", "very", "happy.",
    };
    public int LastTokens, LastPrompt, LastMs;

    public static List<string> Words(string s)
    {
        var list = new List<string>();
        foreach (var w in s.Split(' '))
            if (w.Length > 0) list.Add(w);
        return list;
    }

    public Queue<string> Begin(string prompt, int max)
    {
        LastPrompt = Words(prompt).Count + 1;
        LastTokens = 0;
        LastMs = 1;
        var q = new Queue<string>();
        int start = prompt.Length % 3;
        for (int i = 0; i < max; i++) q.Enqueue((prompt.Length == 0 && i == 0 ? "" : " ") + Story[(start + i) % Story.Length]);
        return q;
    }

    public string Generate(string prompt, int max)
    {
        var q = Begin(prompt, max);
        var sb = new System.Text.StringBuilder();
        while (q.Count > 0) { sb.Append(q.Dequeue()); LastTokens++; }
        return sb.ToString();
    }
}

/// <summary>Computer vision on pictures held as <c>int[]</c> of 0xAARRGGBB
/// (the format of Window.Blit and Buitenzorg.Media.Picture), done by the host
/// on the device and in C# elsewhere.</summary>
public static class Vision
{
    /// <summary>Sobel edge strength as a gray picture: bright = a strong edge.</summary>
    public static int[] Edges(int[] argb, int width, int height)
    {
        var dst = new int[width * height];
        if (AiNative.Present) { AiNative.AiEdges(argb, width, height, dst); return dst; }
        var l = new int[width * height];
        for (int i = 0; i < l.Length; i++) l[i] = Luma(argb[i]);
        for (int y = 1; y < height - 1; y++)
            for (int x = 1; x < width - 1; x++)
            {
                int o = y * width + x;
                int gx = -l[o - width - 1] - 2 * l[o - 1] - l[o + width - 1] + l[o - width + 1] + 2 * l[o + 1] + l[o + width + 1];
                int gy = -l[o - width - 1] - 2 * l[o - width] - l[o - width + 1] + l[o + width - 1] + 2 * l[o + width] + l[o + width + 1];
                int v = Math.Min(255, (Math.Abs(gx) + Math.Abs(gy)) / 2);
                dst[o] = unchecked((int)0xFF000000) | v << 16 | v << 8 | v;
            }
        for (int i = 0; i < dst.Length; i++) if (dst[i] == 0) dst[i] = unchecked((int)0xFF000000);
        return dst;
    }

    /// <summary>The picture in shades of gray (alpha kept).</summary>
    public static int[] Grayscale(int[] argb, int width, int height)
    {
        var dst = new int[width * height];
        if (AiNative.Present) { AiNative.AiGray(argb, width, height, dst); return dst; }
        for (int i = 0; i < dst.Length; i++)
        {
            int v = Luma(argb[i]);
            dst[i] = (argb[i] & unchecked((int)0xFF000000)) | v << 16 | v << 8 | v;
        }
        return dst;
    }

    /// <summary>How many pixels fall in each of <paramref name="bins"/> brightness ranges.</summary>
    public static int[] Histogram(int[] argb, int bins = 16)
    {
        var b = new int[Math.Max(1, bins)];
        if (AiNative.Present) { AiNative.AiHistogram(argb, b); return b; }
        foreach (int p in argb) b[Math.Min(b.Length - 1, Luma(p) * b.Length / 256)]++;
        return b;
    }

    /// <summary>Average edge strength 0..255: a rough "how detailed / how sharp" score.</summary>
    public static int Sharpness(int[] argb, int width, int height)
    {
        var e = Edges(argb, width, height);
        long sum = 0;
        foreach (int p in e) sum += p & 0xFF;
        return e.Length == 0 ? 0 : (int)(sum / e.Length);
    }

    static int Luma(int p) => ((p >> 16 & 0xFF) * 77 + (p >> 8 & 0xFF) * 150 + (p & 0xFF) * 29) >> 8;
}

/// <summary>The machine's compute backend (what <see cref="Accelerator.Auto"/> uses).</summary>
public static class ComputeDevice
{
    /// <summary>The backend's name ("Intel render engine", "V3D", "CPU reference"),
    /// "" when the kernel has none, "simulasi" off the device.</summary>
    public static string Name => AiNative.Present ? AiNative.AiCompute() : "simulasi";
}
