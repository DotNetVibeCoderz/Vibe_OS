                ["main.cs"] = """
                // __APPNAME__ — console app for Buitenzorg OS.
                // Build: compile with bflat --stdlib:zero and link with bzstart.rs
                // (see scripts/build-hello-csharp.ps1), then run from the shell.

                using System;
                using System.Runtime.InteropServices;

                class Program
                {
                    [DllImport("*")] static extern unsafe void bz_write(byte* buf, ulong len);

                    static int Add(int a, int b) => a + b;

                    // zerolib has no ToString()/string concat: format digits by hand
                    // into a stackalloc'd byte buffer and write it out directly.
                    static unsafe void Line(string label, int value)
                    {
                        byte* buf = stackalloc byte[96];
                        int i = 0;
                        for (int k = 0; k < label.Length && i < 80; k++) buf[i++] = (byte)label[k];
                        if (value < 0) { buf[i++] = (byte)'-'; value = -value; }
                        if (value == 0) buf[i++] = (byte)'0';
                        else
                        {
                            byte* d = stackalloc byte[12];
                            int j = 0;
                            while (value > 0 && j < 12) { d[j++] = (byte)('0' + (value % 10)); value /= 10; }
                            while (j > 0) buf[i++] = d[--j];
                        }
                        buf[i++] = (byte)'\n';
                        bz_write(buf, (ulong)i);
                    }

                    static void Main()
                    {
                        Console.WriteLine("__APPNAME__: halo dari ring 3!");

                        int total = 0;
                        for (int i = 1; i <= 5; i++) total = Add(total, i);
                        Line("__APPNAME__: 1..5 = ", total);

                        Console.WriteLine(total == 15
                            ? "MILESTONE: APP OK"
                            : "MILESTONE: APP FAIL");
                    }
                }
                """,
                ["app.manifest"] = Manifest("consoleapp", "__APPNAME__", "console", "csharp"),
