/// <summary>One starter project template: a description plus the files it drops
/// into a new project folder. File names and contents may use the placeholders
/// <c>__APPNAME__</c> (display name), <c>__NAME83__</c> (8.3 device name) and
/// <c>__BZROOT__</c> (the Buitenzorg checkout, for managed project references).</summary>
public sealed record ProjectTemplate(
    string Id,
    string Title,
    string Language,
    string Summary,
    IReadOnlyDictionary<string, string> Files,
    AppKind Kind = AppKind.Native)
{
    /// <summary>The file the editor should open after scaffolding.</summary>
    public string MainFile => Files.Keys.FirstOrDefault(f => f.EndsWith("Program.cs"))
        ?? Files.Keys.First(f => !f.EndsWith(".manifest") && !f.EndsWith(".md") && !f.EndsWith(".csproj"));

    public string KindLabel => Kind switch
    {
        AppKind.Native => "Native",
        AppKind.Managed => "Managed",
        _ => "Skrip",
    };

    /// <summary>What the build produces on /disk, e.g. "NAME.DLL".</summary>
    public string Artifact => Kind switch
    {
        AppKind.Native => "ELF",
        AppKind.Managed => "DLL",
        _ => Language switch { "Python" => "PY", "TypeScript" => "TS", _ => "JS" },
    };
}

/// <summary>The catalog behind "New Project → From Template" and the AI's
/// <c>ListTemplates</c>/<c>ScaffoldProject</c> kernel functions. Every native
/// C# template compiles under bflat <c>--stdlib:zero</c>; every managed one
/// builds with <c>dotnet build</c> and passes its own <c>--selftest</c>; every
/// script stays inside the in-kernel interpreter's subset.</summary>
public static class ProjectTemplates
{
    public static IReadOnlyList<ProjectTemplate> All { get; } = Build();

    public static ProjectTemplate? Find(string id) =>
        All.FirstOrDefault(t => string.Equals(t.Id, id, StringComparison.OrdinalIgnoreCase));

    /// <summary>Write a template's files into <paramref name="dir"/> (existing
    /// files are left alone). Returns the path of the main source file.</summary>
    public static string Scaffold(ProjectTemplate t, string dir, string appName, string? buitenzorgRoot = null)
    {
        Directory.CreateDirectory(dir);
        var name83 = AppProject.To83(appName);
        var root = (buitenzorgRoot ?? Models.Settings.FindRepoRoot() ?? "").TrimEnd('\\', '/');
        string Fill(string s) => s.Replace("__APPNAME__", appName).Replace("__NAME83__", name83).Replace("__BZROOT__", root);
        string main = "";
        foreach (var (name, body) in t.Files)
        {
            var path = Path.Combine(dir, Fill(name));
            if (name == t.MainFile) main = path;
            if (File.Exists(path)) continue;
            File.WriteAllText(path, Fill(body));
        }
        return main;
    }

