                {
                    static void Main()
                    {
                        Console.WriteLine("__APPNAME__: papan permainan...");
                        Font font = Font.Default();
                        UIHost host = new UIHost("__APPNAME__", 280, 320);

                        StackPanel root = new StackPanel();
                        root.Padding = 10; root.Spacing = 8;
