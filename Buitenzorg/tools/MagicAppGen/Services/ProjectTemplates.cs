            {
                ["main.cs"] = """
                // __APPNAME__ — grid game for Buitenzorg OS.
                // A custom UIElement renders the board; the engine is plain C#.
                // Compile together with bzui.cs + bzgfx.cs.

                using System;
                using Buitenzorg.Drawing;
                using Buitenzorg.UI;

                sealed class Board : UIElement
                {
                    // Flat value-type array: never an array of references (stelem.ref faults).
                    public readonly int[] Cells = new int[16];
                    Font _font;
                    readonly char[] _num = new char[6];

                    public Board(Font f) { _font = f; }

                    public override void Measure(int aw, int ah)
                    { DesiredW = Width >= 0 ? Width : 260; DesiredH = Height >= 0 ? Height : 260; }

                    // Slide+merge one row to the left; returns true if anything moved.
                    public bool SlideRow(int row)
                    {
                        int b = row * 4;
                        bool moved = false;
                        for (int pass = 0; pass < 3; pass++)
                            for (int i = 0; i < 3; i++)
                                if (Cells[b + i] == 0 && Cells[b + i + 1] != 0)
                                { Cells[b + i] = Cells[b + i + 1]; Cells[b + i + 1] = 0; moved = true; }
                        for (int i = 0; i < 3; i++)
                            if (Cells[b + i] != 0 && Cells[b + i] == Cells[b + i + 1])
                            {
                                Cells[b + i] *= 2; Cells[b + i + 1] = 0; moved = true;
                                for (int j = i + 1; j < 3; j++) { Cells[b + j] = Cells[b + j + 1]; Cells[b + j + 1] = 0; }
                            }
                        return moved;
                    }

                    static Color TileColor(int v) => v switch
                    {
                        0 => new Color(0xFF2A2F3A),
                        2 => new Color(0xFF4A5568),
                        4 => new Color(0xFF3A78D8),
                        8 => new Color(0xFF2FA36B),
                        16 => new Color(0xFFE0A030),
                        _ => new Color(0xFFE0503C),
                    };

                    public override void Render(Graphics g)
                    {
                        if (!Visible) return;
                        g.FillRoundedRectangle(new Color(0xFF1A1E26), X, Y, W, H, 10);
                        int cell = (W - 10) / 4;
                        for (int r = 0; r < 4; r++)
                            for (int c = 0; c < 4; c++)
                            {
                                int v = Cells[r * 4 + c];
                                int x = X + 5 + c * cell, y = Y + 5 + r * cell;
                                g.FillRoundedRectangle(TileColor(v), x + 3, y + 3, cell - 6, cell - 6, 8);
                                if (v == 0) continue;
                                int n = 0, t = v;
                                while (t > 0) { _num[n++] = (char)('0' + t % 10); t /= 10; }
                                for (int i = 0; i < n / 2; i++) { char tmp = _num[i]; _num[i] = _num[n - 1 - i]; _num[n - 1 - i] = tmp; }
                                g.DrawChars(_font, _num, n, Color.White,
                                            x + cell / 2 - n * 4, y + cell / 2 - 4);
                            }
                    }
                }

