using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace MagicAppGen.Services;

/// <summary>One starter project template: a description plus the files it drops
/// into a new project folder.</summary>
public sealed record ProjectTemplate(
    string Id,
    string Title,
    string Language,
    string Summary,
    IReadOnlyDictionary<string, string> Files)
{
    /// <summary>The file the editor should open after scaffolding.</summary>
    public string MainFile => Files.Keys.First(f => !f.EndsWith(".manifest") && !f.EndsWith(".md"));
}

/// <summary>The catalog behind "New Project → From Template" and the AI's
/// <c>ListTemplates</c>/<c>ScaffoldProject</c> kernel functions. Every C#
/// template compiles under bflat <c>--stdlib:zero</c>: no static reference
/// fields, no <c>object[]</c> element stores, no <c>ToString()</c>/concat.</summary>
public static class ProjectTemplates
{
    public static IReadOnlyList<ProjectTemplate> All { get; } = Build();

    public static ProjectTemplate? Find(string id) =>
        All.FirstOrDefault(t => string.Equals(t.Id, id, StringComparison.OrdinalIgnoreCase));

    /// <summary>Write a template's files into <paramref name="dir"/> (existing
    /// files are left alone). Returns the path of the main source file.</summary>
    public static string Scaffold(ProjectTemplate t, string dir, string appName)
    {
        Directory.CreateDirectory(dir);
        foreach (var (name, body) in t.Files)
        {
            var path = Path.Combine(dir, name);
            if (File.Exists(path)) continue;
            File.WriteAllText(path, body.Replace("__APPNAME__", appName));
        }
        return Path.Combine(dir, t.MainFile);
    }

    static string Manifest(string id, string name, string type, string lang) => $$"""
    {
      "id": "com.example.{{id}}",
      "name": "{{name}}",
      "type": "{{type}}",
      "language": "{{lang}}",
      "version": "0.1.0",
      "permissions": [],
      "theme": "system"
    }
    """;

    static string Readme(string title, string how) => $"""
    # __APPNAME__ — {title}

    Generated by **MagicAppGen** (Jack - The Code Bender) for Buitenzorg OS,
    made by Gravicode Studios, led by Kang Fadhil.

    ## Build & run

    {how}

    C# apps are compiled with bflat `--stdlib:zero` plus the `bzstart.rs` shim
    (see `scripts/build-hello-csharp.ps1`), so they run in ring 3 with no GC.
    Keep the zerolib rules in mind: no static reference fields, no
    method-group→delegate conversions, no storing references into `object[]`
    elements, and no `new string()`/`ToString()`/string concatenation.
    """;

